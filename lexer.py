import re

# Keywords in our grammar
KEYWORDS = {
    "def", "begin", "end", "return", "print"
}

# Token patterns based on grammar.txt
TOKEN_SPECIFICATION = [
    ("number",  r"\d+(\.\d+)?"),
    ("id",      r"[a-zA-Z_][a-zA-Z0-9_]*"),
    ("OP",      r"[=+\-*/]"),
    ("SYMBOL",  r"[(),;]"),
    ("NEWLINE", r"\n"),
    ("SKIP",    r"[ \t\r]+"),
    ("INVALID", r"."),
]


def tokenize(code):
    tokens = []
    line_number = 1

    pattern = "|".join(
        f"(?P<{name}>{regex})"
        for name, regex in TOKEN_SPECIFICATION
    )

    for match in re.finditer(pattern, code):
        token_type = match.lastgroup
        token_value = match.group()

        if token_type == "NEWLINE":
            line_number += 1
            continue

        elif token_type == "SKIP":
            continue

        elif token_type == "INVALID":
            raise SyntaxError(
                f"Invalid character '{token_value}' "
                f"at line {line_number}"
            )

        elif token_type == "id":
            if token_value in KEYWORDS:
                token_type = token_value

        elif token_type == "OP" or token_type == "SYMBOL":
            token_type = token_value

        tokens.append((token_type, token_value))

    return tokens


if __name__ == "__main__":
    print("Enter your program.")
    print("Type ENDINPUT on a new line to finish:")

    lines = []

    while True:
        line = input()

        if line == "ENDINPUT":
            break

        lines.append(line)

    source_code = "\n".join(lines)

    try:
        result = tokenize(source_code)

        print("\nTokens generated by the lexer:")

        for token in result:
            print(token)

    except SyntaxError as error:
        print("Lexer Error:", error)
