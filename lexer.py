import re

KEYWORDS = {
    "def", "begin", "end", "return", "print"
}

TOKEN_SPECIFICATION = [
    ("NUMBER",      r"\d+(\.\d+)?"),
    ("IDENTIFIER",  r"[a-zA-Z_][a-zA-Z0-9_]*"),
    ("OPERATOR",    r"==|!=|<=|>=|[+\-*/%=<>]"),
    ("PUNCTUATION", r"[(),:;{}]"),
    ("NEWLINE",     r"\n"),
    ("SKIP",        r"[ \t\r]+"),
    ("INVALID",     r"."),
]

def tokenize(code):
    tokens = []
    line_number = 1

    pattern = "|".join(
        f"(?P<{name}>{regex})"
        for name, regex in TOKEN_SPECIFICATION
    )

    for match in re.finditer(pattern, code):
        token_type = match.lastgroup
        token_value = match.group()

        if token_type == "NEWLINE":
            line_number += 1
            continue

        elif token_type == "SKIP":
            continue

        elif token_type == "INVALID":
            raise SyntaxError(
                f"Invalid character '{token_value}' "
                f"at line {line_number}"
            )

        elif token_type == "IDENTIFIER":
            if token_value in KEYWORDS:
                token_type = "KEYWORD"

        tokens.append((token_type, token_value))

    return tokens


if __name__ == "__main__":
    print("Enter your function definition.")
    print("Type ENDINPUT on a new line to finish:")

    lines = []

    while True:
        line = input()

        if line == "ENDINPUT":
            break

        lines.append(line)

    sample_program = "\n".join(lines)

    try:
        result = tokenize(sample_program)

        print("\nTokens generated by the lexer:")
        for token in result:
            print(token)

    except SyntaxError as error:
        print("Lexer Error:", error)
